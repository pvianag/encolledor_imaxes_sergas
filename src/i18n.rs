#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Gl,
    Es,
    En,
    Fr,
    Pt,
}

impl Lang {
    pub fn all() -> &'static [Lang] {
        &[Lang::Gl, Lang::Es, Lang::En, Lang::Fr, Lang::Pt]
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::Gl => "gl",
            Lang::Es => "es",
            Lang::En => "en",
            Lang::Fr => "fr",
            Lang::Pt => "pt",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            Lang::Gl => "Galego",
            Lang::Es => "Español",
            Lang::En => "English",
            Lang::Fr => "Français",
            Lang::Pt => "Português",
        }
    }

    pub fn from_code(code: &str) -> Self {
        match code.to_ascii_lowercase().as_str() {
            "es" => Lang::Es,
            "en" => Lang::En,
            "fr" => Lang::Fr,
            "pt" => Lang::Pt,
            _ => Lang::Gl,
        }
    }
}

